async function seed(page: Page) {
  await page.addInitScript(() => {
    localStorage.setItem('newtone-public-release-cutover-v1', 'center-v1')
    if (!localStorage.getItem('newtone-player-save-v1')) localStorage.setItem('newtone-player-save-v1', JSON.stringify({ currentSceneId: 'commercial-cafe', phoneDevice: 'inner', sceneState: { 'commercial-cafe': { commercialCafeStoryStatus: 'complete' } }, updatedAt: 100 }))
  })
  await page.goto('/?scene=commercial-cafe')
}
async function capture(page: Page, info: TestInfo, name: string) {
  await page.locator('.world-phone').evaluate(e => Promise.all(e.getAnimations({ subtree: true }).filter(a => Number(a.effect?.getComputedTiming().iterations) !== Infinity).map(a => a.finished.catch(() => {}))))
  await page.screenshot({ path: process.env.PHONE_SCREENSHOT_DIR ? join(process.env.PHONE_SCREENSHOT_DIR, `${info.title.split(' ')[0]}-round2-${name}.png`) : info.outputPath(`${name}.png`) })
}
