test('Reduced Motion and repeated navigation complete without a stuck animation', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' }); await seed(page)
  const phone = page.locator('.world-phone')
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.getByLabel('打开手机').click()
  expect(await phone.locator('[data-weather=rainy]').first().evaluate(e => getComputedStyle(e, '::before').animationName)).toBe('none')
  for (const app of ['map','contacts','ride','contacts']) {
    await phone.locator(`[data-app=${app}]`).click()
    await expect(phone.locator(`[data-app-view=${app}]`)).toBeVisible()
    await phone.getByLabel('返回手机主屏').dblclick()
    await expect(phone.getByLabel('剧情日历')).toBeVisible()
  }
  await phone.locator('[data-app=contacts]').click(); await phone.locator('.world-phone__contact-row').click()
  await phone.getByRole('button', { name: '信息', exact: true }).click()
  await expect(phone.getByRole('region', { name: '与老周的短信' })).toBeVisible()
  await phone.getByLabel('返回联系人').click()
  await expect(phone.getByRole('region', { name: '老周联系人详情' })).toBeVisible()
  await phone.getByLabel('返回联系人').click()
  await expect(phone.locator('.world-phone__contact-row')).toHaveCount(1)
  await expect(phone).not.toContainText('若雨')
  expect(errors).toEqual([])
})
test('real driver deadline only signals capsule, persists unread and opens notification on demand', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 }); await seed(page)
  const phone = page.locator('.world-phone')
  await page.getByLabel('打开手机').click(); await phone.locator('[data-app=ride]').click()
  await phone.getByRole('button', { name: /中枢院.*从当前位置出发/ }).click()
  await phone.getByRole('button', { name: /^快车/ }).click()
  await phone.getByRole('button', { name: '确认叫车', exact: true }).click()
  await expect(phone.locator('[data-ride-order=true]')).toContainText('司机正在路上')
  await capture(page, info, 'driver-distance')
  await page.keyboard.press('Escape'); await expect(phone).toHaveAttribute('data-phone-phase', 'closed')
  await expect(phone.locator('.world-phone__notification-dot')).toBeVisible({ timeout: 30000 })
  await expect(phone).toHaveAttribute('data-phone-phase', 'closed')
  await expect(page.locator('.world-phone__dismiss-region')).toHaveCount(0)
  await expect(phone.locator('.world-phone__notification-flow')).toHaveCount(0)
  await capture(page, info, 'driver-capsule')
  await page.getByLabel('打开手机').click()
  await expect(phone.getByLabel('手机通知')).toContainText('司机已到达')
  await phone.locator('.world-phone__lock-hint').click()
  await expect(phone.locator('[data-app=ride]')).toHaveAttribute('data-unread', 'true')
  await page.reload(); await page.getByLabel('打开手机').click()
  await expect(phone.getByLabel('手机通知')).toContainText('司机已到达')
  await phone.locator('[data-notification-app=ride]').click()
  await expect(phone.locator('[data-ride-order=true]')).toContainText('司机已到达')
  await phone.getByLabel('放大地图').click(); await phone.getByLabel('放大地图').click()
  const sizes = await phone.locator('.world-phone__map-marker span').evaluateAll(elements => elements.map(e => parseFloat(getComputedStyle(e).fontSize)))
  expect(sizes.every(size => size >= 11 && size <= 12)).toBe(true)
  await capture(page, info, 'waiting-map-zoom')
  await phone.getByLabel('返回手机主屏').click()
  await expect(phone.locator('[data-app=ride]')).toHaveAttribute('data-unread', 'false')
  await page.keyboard.press('Escape'); await expect(phone.locator('.world-phone__notification-dot')).toHaveCount(0)
})
