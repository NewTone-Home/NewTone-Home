function pointInPolygon(x: number, y: number, polygon: ActivationRegion): boolean {
  let inside = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i, i += 1) {
    const [xi, yi] = polygon[i]
    const [xj, yj] = polygon[j]
    const crosses = (yi > y) !== (yj > y)
      && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi
    if (crosses) inside = !inside
  }
  return inside
}

/**
 * 已描边地点只在轮廓内响应；未配置轮廓的地点保持原矩形命中，等待后续补画。
 */
export function isInsidePlaceActivationRegion(placeId: string, x: number, y: number): boolean {
  const regions = REGIONS_BY_PLACE_ID[placeId]
  if (!regions) return true
  if (!Number.isFinite(x) || !Number.isFinite(y) || x < 0 || x > 1 || y < 0 || y > 1) return false
  return regions.some(region => pointInPolygon(x, y, region))
}
