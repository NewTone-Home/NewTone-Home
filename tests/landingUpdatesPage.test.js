import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL(path, import.meta.url), 'utf8')
const page = read('../src/components/LandingUpdatesPage.jsx')
const styles = read('../src/components/LandingUpdatesPage.css')
const pageShellStyles = read('../src/components/PageShell.css')
const entryStyles = read('../src/views/LandingUpdatesEntry.css')
const entrySurface = read('../src/components/EntrySurface.jsx')
const audit = read('../src/services/runtimeAudit.js')

describe('Landing updates page button contract', () => {
  it('uses the shared button and waits for the page phase before showing it', () => {
    expect(page).toContain("import EntryButtonSurface from './EntryButtonSurface'")
    expect(page).toContain('const interactive = phase === UPDATES_PHASE.UPDATES')
    expect(page).toContain('visible={interactive}')
    expect(page).toContain('entryId="landing-updates-return"')
    expect(page).toContain('materialMode="background"')
    expect(page).toContain('onActionComplete={handleReturnComplete}')
    expect(page).not.toContain('useReducer')
    expect(page).not.toContain('LandingUpdatesReturnEntry')
    expect(page).not.toContain('LandingEntryArrow')
  })

  it('has no global wheel, touch, or pointer gesture route', () => {
    expect(page).not.toContain('addEventListener')
    expect(page).not.toContain('onPointerLeave')
    expect(page).not.toContain('resolveUpdatesWheelIntent')
    expect(page).not.toContain('resolveUpdatesTouchIntent')
    expect(styles).not.toContain('data-return-state')
    expect(styles).not.toContain('landing-updates-page__return-backdrop')
  })

  it('records one return intent only after the shared exit completes', () => {
    expect(page).toContain('returnIssuedRef.current')
    expect(page).toContain("recordRuntimeAudit('updates-return-intent'")
    expect(page).toContain('onReturnRequested?.()')
    expect(styles).toContain('left: clamp(1.25rem, 8vw, 8rem)')
    expect(styles).toContain('bottom: clamp(1.25rem, 6vh, 3.5rem)')
    expect(audit).toContain('window.NT_AUDIT')
  })

  it('renders the selected announcement layout and copy', () => {
    expect(page).toContain('landing-updates-page__timeline')
    expect(page).toContain('landing-updates-page__timeline-trigger')
    expect(page).toContain('aria-expanded={expanded}')
    expect(page).toContain('setExpandedVersion(current => current === version ? null : version)')
    expect(page).toContain('landing-updates-page__summary')
    expect(page).toContain('landing-updates-page__details')
    expect(page).toContain("version: 'v0.2.2'")
    expect(page).toContain("date: '2026.10.12'")
    expect(page).toContain("dateTime: '2026-10-12'")
    expect(page).toContain('这次没有加入新的宇宙，也没有打开什么新的神秘入口。')
    expect(page).toContain('我们优化了不少体验。')
    expect(page).toContain('· 重新设计了手机，现在更好看，也更好用了。')
    expect(page).toContain('· 优化了部分视觉效果和交互体验。')
    expect(page).toContain('接下来，我们计划逐步推进以下内容：')
    expect(page).toContain('· 不同设备的适配')
    expect(page).toContain('· 不同语言的适配')
    expect(page).toContain('· 新的场景和新的剧情')
    expect(page).toContain('· 用户注册系统')
    expect(page).toContain('No new universe this time. No secret doorway, either.')
    expect(page).toContain("We've made quite a few improvements to the experience.")
    expect(page).toContain("· We've redesigned the in-world phone. It looks better and is easier to use.")
    expect(page).toContain("· We've also refined some of the visuals and interactions.")
    expect(page).toContain("Here's what we're planning to work on next:")
    expect(page).toContain('· Better support for different devices')
    expect(page).toContain('· Support for more languages')
    expect(page).toContain('· New scenes and story content')
    expect(page).toContain('· User registration system')
    expect(page).toContain("version: 'v0.1.2'")
    expect(page).toContain("version: 'v0.1.1'")
    expect(page).toContain("version: 'v0.2.0'")
    expect(page).toContain("date: '2026.09.12'")
    expect(page).toContain('本次我们重新装修了宇宙空间，重新布置了入口。')
    expect(page).toContain('· NewTone 现在已经可以开始探索了。')
    expect(page).toContain('· 我们创建了第一批场景和互动元素。')
    expect(page).toContain('希望能满足大家的好奇心。')
    expect(page).toContain('This time, we renovated the universe and redesigned its entrance.')
    expect(page).toContain('· NewTone is now ready to explore.')
    expect(page).toContain('· We created the first set of scenes and interactive elements.')
    expect(page).toContain('We hope it satisfies your curiosity.')
    expect(page).toContain('LANDING_UPDATES.map')
    expect(page).toContain('expandedVersion')
    expect(page).toContain('landing-updates-page__timeline-heading')
    expect(page).toContain('landing-updates-page__timeline-version')
    expect(styles).toContain('.landing-updates-page__timeline::before')
    expect(styles).toContain('animation: updates-timeline-dot-pulse 1.4s ease-in-out infinite')
    expect(styles).toContain('animation: updates-timeline-dot-ring 1.4s ease-out infinite')
    expect(styles).toContain('@keyframes updates-timeline-dot-pulse')
    expect(styles).toContain('@keyframes updates-timeline-dot-ring')
    expect(page).not.toContain('landing-updates-page__placeholder')
    expect(page).not.toContain('<h1>')
    expect(page).toContain('这次没有加入新的宇宙，神秘入口正在筹备中。')
    expect(page).toContain('同时，我们把阅读模式合并成了一个，现在不再分成两个模式。')
    expect(page).toContain('并且优化了阅读体验和操作体验。')
    expect(page).toContain('No new universe was added this time. The mysterious entrance is still in the works.')
    expect(page).toContain('We combined the reading modes into one, so there are no longer two separate modes.')
    expect(page).toContain('We also improved the reading and interaction experience.')
    expect(page).toContain('No new universe this time. No secret doorway, either.')
    expect(page).toContain('We also improved performance across a wider range of devices.')
    expect(entrySurface).toContain('language={language}')
  })

  it('keeps the Landing and updates surface transitions on one timing contract', () => {
    expect(styles).toContain('animation: updates-page-enter 720ms')
    expect(styles).toContain('animation: updates-page-return 720ms')
    expect(styles).toContain('.landing-updates-page__timeline-dot {\n    animation: none;\n  }')
    expect(entryStyles).toContain('animation: landing-updates-surface-exit 720ms')
    expect(entryStyles).toContain('animation: landing-updates-surface-return 720ms')
    expect(styles).not.toContain('120ms forwards')
  })

  it('keeps expanded updates inside a bounded, vertically scrollable viewport on desktop and touch screens', () => {
    expect(pageShellStyles).toContain('height: 100dvh')
    expect(pageShellStyles).toContain('overflow: hidden')
    expect(styles).toContain('height: 100%')
    expect(styles).toContain('min-height: 0')
    expect(styles).toContain('max-height: 100%')
    expect(styles).toContain('overflow-x: hidden')
    expect(styles).toContain('overflow-y: auto')
    expect(styles).toContain('overscroll-behavior-y: contain')
    expect(styles).toContain('-webkit-overflow-scrolling: touch')
    expect(styles).toContain('align-items: safe center')
    expect(styles).toContain('height: auto')
    expect(styles).toContain('min-height: 100%')
    expect(styles).toContain('box-sizing: border-box')
    expect(styles).toContain('.landing-updates-page__details-shell > .landing-updates-page__details')
    expect(styles).toContain('overflow: hidden')
  })
})
